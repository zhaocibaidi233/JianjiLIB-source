# Generate launcher/Version.cs from ..\VERSION so the exe version can never drift.
#
# Why: the assembly attributes used to be hand-edited in Launcher.cs. Twice in one
# day they lagged behind VERSION (1.1.11 while VERSION said 1.1.16), and the drift
# is invisible until someone right-clicks the exe. A build step cannot forget.
#
# Usage: pwsh -NoProfile -File version-gen.ps1
# Output: launcher\Version.cs (generated; gitignored)

$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$verFile = Join-Path $here '..\VERSION'

if (-not (Test-Path $verFile)) {
    Write-Error "VERSION not found at $verFile"
    exit 1
}

$ver = (Get-Content $verFile -Raw).Trim()
if (-not $ver) {
    Write-Error 'VERSION is empty'
    exit 1
}

# AssemblyVersion needs four numeric parts: 1.2.3 -> 1.2.3.0
if ($ver -match '^\d+\.\d+\.\d+\.\d+$') {
    $ver4 = $ver
} else {
    $ver4 = "$ver.0"
}

$lines = @(
    '// <auto-generated>'
    '//   Generated by version-gen.ps1 from ..\VERSION -- do not edit.'
    '// </auto-generated>'
    'using System.Reflection;'
    ''
    "[assembly: AssemblyVersion(""$ver4"")]"
    "[assembly: AssemblyFileVersion(""$ver4"")]"
    "[assembly: AssemblyInformationalVersion(""$ver"")]"
)

$out = Join-Path $here 'Version.cs'
# UTF-8 without BOM: csc is fine with it, and the repo convention is no BOM.
[System.IO.File]::WriteAllLines($out, $lines, (New-Object System.Text.UTF8Encoding $false))

Write-Host "[version] $ver (assembly $ver4)"
